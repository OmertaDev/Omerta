import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const output = path.join(root, 'public/art/hook-campaign');
const manifestPath = path.join(output, 'fal-manifest.json');
const model = 'bytedance/seedance-2.5/text-to-video';
const look = 'Eight second single continuous shot. Vertical 9:16 premium 1940s noir game campaign, black stone, antique brass, ivory light and restrained teal, cinematic realism, slow controlled dolly, volumetric haze, deep blacks, no flashing. Keep main subject in upper half and lower half dark for later typography. No text, lettering, currency symbols, logos, charts, watermark, or UI. This is a cinematic metaphor, not gameplay footage.';
const catalog = [
  {id: 'city', prompt: `An immense art deco vault door slowly opens onto a meticulously crafted miniature rain-soaked harbor city. Gold-lit windows illuminate one district at a time. A single brass ledger mechanism in the foreground distributes a finite set of tokens into four channels, preserving every token. Camera pushes through the circular vault frame toward the city. ${look}`},
  {id: 'reserve', prompt: `Inside a noir treasury, a monumental seven-compartment brass reserve desk sits beneath a narrow shaft of ivory light. Each compartment contains a distinct finite quantity of dark gold tokens or teal glass counters. A precision mechanical arm moves one existing stack between compartments, never multiplying assets. Camera makes a slow arc past smoked glass into a grand symmetrical view. ${look}`},
  {id: 'turf', prompt: `A cinematic overhead view of a miniature 1940s city on a black marble strategy table. Four distinct family signet rings rest at its edges. Brass borders trace adjacent city blocks. A small teal beacon shifts from one block to the next while the substantial underlying buildings and foundation remain in place. Slow descending camera reveals exquisite wet streets and warm windows. No violence. ${look}`},
];
fs.mkdirSync(output, {recursive: true});
const estimatedUsd = 3 * 8 * 0.473;
fs.writeFileSync(path.join(output, 'fal-prompts.json'), JSON.stringify({model, resolution: '720p', duration: '8', aspect_ratio: '9:16', generate_audio: false, estimatedUsd, estimateSource: 'https://fal.ai/models/bytedance/seedance-2.5/text-to-video', catalog}, null, 2));
if (process.argv.includes('--plan')) {
  console.log(JSON.stringify({plates: catalog.length, estimatedUsd, credentialsNeeded: 'FAL_KEY', output}));
  process.exit(0);
}
const key = process.env.FAL_KEY?.trim();
if (!key) throw new Error('FAL_KEY is required; no generation was submitted.');
const headers = {Authorization: `Key ${key}`, 'Content-Type': 'application/json'};
const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : {model, estimatedUsd, jobs: {}};
const save = () => {
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
  const complete = catalog.filter(a => manifest.jobs[a.id]?.status === 'downloaded').map(a => a.id);
  fs.writeFileSync(path.join(root, 'brand/hype-flywheel-video/src/hook-campaign/media.ts'), `// Generated by scripts/generate-hook-plates.mjs\nexport const motionPlates: string[] = ${JSON.stringify(complete)};\n`);
};
const read = async (url, auth = true) => {
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const response = await fetch(url, {headers: auth ? headers : {}, signal: AbortSignal.timeout(45000)});
      if (response.ok) return response;
      if (response.status < 500 && response.status !== 429) throw new Error(`Read failed: HTTP ${response.status}`);
    } catch (error) {if (attempt === 4) throw error;}
    await new Promise(resolve => setTimeout(resolve, 3000 * (attempt + 1)));
  }
  throw new Error('Read retry budget exhausted');
};
for (const asset of catalog) {
  let job = manifest.jobs[asset.id];
  if (job?.status === 'downloaded' && fs.existsSync(path.join(output, `${asset.id}.mp4`))) continue;
  if (!job) {
    // Persist before POST. An ambiguous submission must be reconciled, never blindly retried.
    job = {status: 'submitting', prompt: asset.prompt, submittedAt: new Date().toISOString()};
    manifest.jobs[asset.id] = job;
    save();
    const response = await fetch(`https://queue.fal.run/${model}`, {method: 'POST', headers, body: JSON.stringify({prompt: asset.prompt, resolution: '720p', duration: '8', aspect_ratio: '9:16', generate_audio: false}), signal: AbortSignal.timeout(60000)});
    if (!response.ok) throw new Error(`Submission HTTP ${response.status}; inspect job before retrying.`);
    const result = await response.json();
    if (!result.request_id || !result.status_url || !result.response_url) throw new Error('Incomplete queue receipt; reconcile with fal dashboard.');
    Object.assign(job, {status: 'queued', requestId: result.request_id, statusUrl: result.status_url, responseUrl: result.response_url});
    save();
  }
  if (!job.requestId) throw new Error(`${asset.id}: ambiguous previous submission; reconcile in fal dashboard before retry.`);
  let done = false;
  for (let attempt = 0; attempt < 180; attempt++) {
    const status = await (await read(job.statusUrl)).json();
    if (status.status === 'COMPLETED') {done = true; break;}
    if (status.status === 'FAILED') throw new Error(`${asset.id}: generation failed; no automatic resubmission.`);
    if (attempt % 6 === 0) console.log(`${asset.id}: ${status.status}`);
    await new Promise(resolve => setTimeout(resolve, 10000));
  }
  if (!done) throw new Error('Queue timeout; request retained for resume.');
  const result = await (await read(job.responseUrl)).json();
  if (!result.video?.url) throw new Error('Completed result has no video URL.');
  const bytes = Buffer.from(await (await read(result.video.url, false)).arrayBuffer());
  fs.writeFileSync(path.join(output, `${asset.id}.mp4`), bytes);
  Object.assign(job, {status: 'downloaded', bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex'), completedAt: new Date().toISOString()});
  save();
  console.log(`${asset.id}: downloaded`);
}
console.log('All three motion plates are ready.');
