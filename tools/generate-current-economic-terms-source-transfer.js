// Build the source-only bridge from immutable Git objects, never from the working tree.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';

const source = 'b216e52081c378b879f3056bed9b76f5565179ef';
const predecessor = 'b35dd222054f0c5f3ca814f228dd7d9a46c58ae9';
const domains = [
  'docs/WIKI.md', 'package.json', 'public/index.html', 'public/wiki.html', 'schema.sql',
  'src/agentgateway.js', 'src/chain.js', 'src/preflight.js', 'src/routes/modtools.js',
  'src/rules.tail.js', 'src/server.js', 'test/client.js', 'test/gates.js',
];
const git = (...args) => execFileSync('git',['--no-replace-objects',...args],{
  encoding:'utf8', maxBuffer:32*1024*1024, windowsHide:true,
});
const sha = text => createHash('sha256').update(text).digest('hex');
const lineOffsets = text => [0,...Array.from(text.matchAll(/\n/g), match => match.index+1)];

function read(revision,file) {
  const text = git('show',revision+':'+file);
  const [mode,type,blob] = git('ls-tree',revision,'--',file).trim().split(/\s+/);
  assert(['100644','100755'].includes(mode));
  assert.equal(type,'blob');
  return {text,pin:{mode,blob,sha256:sha(text),bytes:Buffer.byteLength(text)}};
}

assert.deepEqual(process.argv.slice(2),['--write']);
git('merge-base','--is-ancestor',predecessor,source);
git('merge-base','--is-ancestor',source,'HEAD');
const files = {};
for (const file of domains) {
  const current = read(source,file), old = read(predecessor,file);
  const offsets = lineOffsets(current.text), oldOffsets = lineOffsets(old.text);
  const diff = git('diff','--no-ext-diff','--no-textconv','--unified=0',predecessor,source,'--',file);
  const inverses = [];
  for (const match of diff.matchAll(/^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@/gm)) {
    const oldCount=Number(match[2]??1), newCount=Number(match[4]??1);
    const oldLine=Number(match[1])-(oldCount ? 1 : 0), newLine=Number(match[3])-(newCount ? 1 : 0);
    const at = offsets[newLine];
    const after = current.text.slice(at,offsets[newLine+newCount]);
    const before = old.text.slice(oldOffsets[oldLine],oldOffsets[oldLine+oldCount]);
    // Trim unchanged line prefixes/suffixes. This keeps one npm-script insertion from copying the entire script.
    let prefix=0, suffix=0;
    const limit=Math.min(before.length,after.length);
    while (prefix<limit && before[prefix]===after[prefix]) prefix++;
    while (suffix<limit-prefix && before[before.length-1-suffix]===after[after.length-1-suffix]) suffix++;
    inverses.push({at:at+prefix,current:after.slice(prefix,after.length-suffix),baseline:before.slice(prefix,before.length-suffix)});
  }
  assert(inverses.length,'Unchanged domain '+file);
  let restored=current.text;
  for (const {at,current:cut,baseline} of inverses.toReversed()) {
    assert.equal(restored.slice(at,at+cut.length),cut);
    restored=restored.slice(0,at)+baseline+restored.slice(at+cut.length);
  }
  assert.equal(restored,old.text);
  files[file]={current:current.pin,baseline:old.pin,inverses};
}
const pin={source,sourceTree:git('rev-parse',source+'^{tree}').trim(),predecessor,
  predecessorTree:git('rev-parse',predecessor+'^{tree}').trim(),files};
writeFileSync(new URL('./current-economic-terms-source-data.js',import.meta.url),
  '// Generated by generate-current-economic-terms-source-transfer.js from the reviewed Git objects.\n'
  +'export const economicTermsPin = '+JSON.stringify(pin,null,2)+';\n');
