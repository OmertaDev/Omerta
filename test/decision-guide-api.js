import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {buildServer} from './server-fixture.js';
const c=vm.createContext({window:{}});vm.runInContext(readFileSync('public/player-experience.js','utf8'),c);
const x=c.window.PlayerExperience,app=await buildServer();
const call=async(method,url,token,payload)=>{const r=await app.inject({method,url,headers:token?{authorization:`Bearer ${token}`}:{},payload});return {code:r.statusCode,body:r.json()};};
const make=async name=>{const {body:{token}}=await call('POST','/v1/auth/guest');assert.equal((await call('POST','/v1/character',token,{name})).code,200);return {token,id:(await call('GET','/v1/me',token)).body.character.id};};
const view=async actor=>(await call('GET','/v1/me',actor.token)).body.character;
try {
 const seller=await make('Guide Seller'),buyer=await make('Guide Buyer');
 await app.pool.query("UPDATE characters SET cash=100000,loc='docks' WHERE id IN ($1,$2)",[seller.id,buyer.id]);
 const {GOODS}=await import('../src/rules.js'),good=GOODS[0].id;
 await app.pool.query('INSERT INTO character_cargo(character_id,good_id,qty) VALUES ($1,$2,20)',[seller.id,good]);
 const post=await call('POST','/v1/market',seller.token,{goodId:good,qty:10,price:101});assert.equal(post.code,200,JSON.stringify(post.body));
 let board=(await call('GET','/v1/market',buyer.token)).body,lot=board.listings.find(l=>l.id===post.body.id);
 let before=await view(buyer),q=x.marketQuote(lot,'2',before,board.levers);
 assert(q.ready);const bought=await call('POST',`/v1/market/${lot.id}/buy`,buyer.token,{qty:q.qty});assert.equal(bought.code,200);
 assert.equal((await view(buyer)).cash,before.cash-q.debit);
 const order=await call('POST','/v1/market/order',buyer.token,{goodId:good,qty:5,price:101});assert.equal(order.code,200,JSON.stringify(order.body));
 board=(await call('GET','/v1/market',seller.token)).body;lot=board.listings.find(l=>l.id===order.body.id);before=await view(seller);q=x.marketQuote(lot,'3',before,board.levers);assert(q.ready);
 const filled=await call('POST',`/v1/market/${lot.id}/fill`,seller.token,{qty:q.qty});assert.equal(filled.code,200);assert.equal((await view(seller)).cash,before.cash+q.net);
 assert.equal(x.marketQuote(lot,'1',await view(buyer),board.levers).ready,false,'own order is unavailable');
 const capacity=(await view(buyer)).cargoCap;
 await app.pool.query('UPDATE character_cargo SET qty=$3 WHERE character_id=$1 AND good_id=$2',[buyer.id,good,capacity-1]);
 board=(await call('GET','/v1/market',buyer.token)).body;lot=board.listings.find(l=>l.id===post.body.id);before=await view(buyer);
 assert.equal(x.marketQuote(lot,'2',before,board.levers).ready,false,'do not promise server-clamped two units');
 q=x.marketQuote(lot,'1',before,board.levers);assert(q.ready);
 assert.equal((await call('POST',`/v1/market/${lot.id}/buy`,buyer.token,{qty:1})).code,200);
 assert.equal((await view(buyer)).cash,before.cash-q.debit);
 await app.pool.query('UPDATE character_cargo SET qty=$3 WHERE character_id=$1 AND good_id=$2',[buyer.id,good,capacity]);
 board=(await call('GET','/v1/market',buyer.token)).body;lot=board.listings.find(l=>l.id===post.body.id);before=await view(buyer);
 assert.equal(x.marketQuote(lot,'1',before,board.levers).ready,false);
 assert.equal((await call('POST',`/v1/market/${lot.id}/buy`,buyer.token,{qty:1})).body.error,'cargo');
 const rules=(await call('GET','/v1/rules',buyer.token)).body;
 const destination=rules.districts.map(d=>d.id || d).find(d=>d!==before.loc);q=x.travel(before,rules.travelCost,destination);assert(q.ready);
 assert.equal((await call('POST',`/v1/travel/${destination}`,buyer.token,{})).code,200);assert.equal((await view(buyer)).cash,q.after);
 console.log('decision API: trade debits, rounded proceeds, cargo refusal and travel match server');
} finally {await app.close();await app.pool.end();}
