import assert from 'node:assert/strict';
import { supplyDue, supplyContractView, requireSupplyContract, recordSupplyDispatch, setSupplyContract } from '../src/supplycontracts.js';
const now = Date.now();
const row = { id: 'cadence', depot_id: 'depot', revision: 1, policy_id: 'policy', enabled: true,
  interval_seconds: 3600, max_cycles: 2, dispatched: 0, next_dispatch_at: new Date(now), expires_at: new Date(now + 7200000), last_order_id: null };
const queries = [];
const client = { query: async (sql, args) => { queries.push({ sql, args }); return { rows: sql.startsWith('SELECT') ? [row] : [] }; } };
assert.equal(supplyDue(row, now - 1), false);
assert.equal(supplyDue(row, now), true);
assert.equal(supplyDue(row, now + 7200000), false);
assert.equal(supplyDue({ ...row, dispatched: 2 }, now), false);
assert.equal(supplyDue({ ...row, enabled: false }, now), false);
assert.equal(supplyDue(row, NaN), false);
assert.equal(supplyContractView(row).gameCashOnly, true);
assert.equal(supplyContractView(null), null);
assert.equal(await requireSupplyContract({ query: async () => ({ rows: [] }) }, { id: 'depot' }, 'policy', now), null);
assert.equal(await requireSupplyContract({ query: async () => ({ rows: [{ ...row, enabled: false }] }) }, { id: 'depot' }, 'different', now), null);
assert.equal(await requireSupplyContract(client, { id: 'depot' }, 'policy', now), row);
await assert.rejects(requireSupplyContract(client, { id: 'depot' }, 'old', now), /authority changed/);
await assert.rejects(requireSupplyContract(client, { id: 'depot' }, 'policy', now - 1), /not due/);
const order = { id: 'order', kind: 'order', depotId: 'depot', escrow: 2000, fee: 20 };
for (const bad of [{}, { ...order, depotId: 'other' }, { ...order, escrow: 0 }, { ...order, fee: NaN }, { ...order, kind: 'noop' }])
  await assert.rejects(recordSupplyDispatch(client, row, bad, now), /actual funded/);
assert.equal(row.dispatched, 0);
await recordSupplyDispatch(client, row, order, now);
assert.equal(row.dispatched, 1);
assert.equal(row.last_order_id, 'order');
assert.equal(supplyDue(row, now), false);
await assert.rejects(recordSupplyDispatch(client, row, order, now + 3600000), /already recorded/);
await recordSupplyDispatch(client, row, { ...order, id: 'order2' }, now + 3600000);
assert.equal(row.dispatched, 2);
assert.equal(supplyDue(row, now + 7199999), false);
assert.equal(queries.filter((q) => q.sql.startsWith('UPDATE')).length, 2);
const depot = { id: 'depot', owner_character: 'owner', bid_price: 500, target_stock: 4, reorder_at: 0, restock_budget: 3000 };
const policy = { id: 'policy', enabled: true, allow_restock: true, expires_at: new Date(now + 7200000), bid_price: 500, target_stock: 4, reorder_at: 0, order_budget: 3000 };
let current = null;
const db = { query: async (sql, args) => {
  if (sql.includes('FROM business_depots')) return { rows: args[1] === 'owner' ? [depot] : [] };
  if (sql.includes('FROM business_operating_policies')) return { rows: [policy] };
  if (sql.startsWith('SELECT')) return { rows: current ? [current] : [] };
  if (sql.startsWith('INSERT')) current = { id: args[0], depot_id: args[1], revision: args[2], policy_id: args[3], enabled: args[4], interval_seconds: args[5], max_cycles: args[6], next_dispatch_at: args[7], expires_at: args[8], dispatched: 0 };
  return { rows: [] };
} };
const terms = { expectedRevision: 0, enabled: true, intervalSeconds: 3600, maxCycles: 2, expiresInSeconds: 7200 };
await assert.rejects(setSupplyContract({ id: 'stranger' }, 'depot', terms, db), /yours/);
for (const bad of [{ ...terms, expectedRevision: '0' }, { ...terms, intervalSeconds: 3599 }, { ...terms, maxCycles: 101 }, { ...terms, enabled: 1 }])
  await assert.rejects(setSupplyContract({ id: 'owner' }, 'depot', bad, db));
assert.equal(current, null);
const saved = await setSupplyContract({ id: 'owner' }, 'depot', terms, db);
assert.equal(saved.contract.policyId, 'policy');
assert.equal(saved.contract.remainingCycles, 2);
await assert.rejects(setSupplyContract({ id: 'owner' }, 'depot', terms, db), /revision/);
policy.enabled = false;
await assert.rejects(setSupplyContract({ id: 'owner' }, 'depot', { ...terms, expectedRevision: 1 }, db), /Authorize/);
assert.equal(current.revision, 1);
const disabled = await setSupplyContract({ id: 'owner' }, 'depot', { ...terms, expectedRevision: 1, enabled: false }, db);
assert.equal(disabled.contract.enabled, false);
assert.equal(disabled.contract.revision, 2);
console.log('Supply cadence bounds, revision, policy, replay and non-monetary dispatch tests passed.');
