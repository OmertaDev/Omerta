import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const ctx=vm.createContext({window:{}});
vm.runInContext(readFileSync(new URL('../public/player-experience.js',import.meta.url),'utf8'),ctx);
const x=ctx.window.PlayerExperience;
const now=Date.parse('2026-10-22T12:00:00Z');
const me={id:'buyer',generation:1,loc:'docks',cash:1000,cargoCap:10,cargo:{booze:3},bank:300,bankInTransit:70};
const listing={id:'lot',sellerId:'seller',kind:'good',good:'booze',district:'docks',qty:8,unitPrice:101,expiresAt:new Date(now+60000).toISOString()};
assert.equal(x.marketQuote(listing,'2',me,{takeBps:200},now).debit,202);
assert.equal(x.marketQuote({...listing,kind:'order',wanted:8},'3',me,{takeBps:200},now).net,296,'seller pays rounded-up take');
for(const qty of ['', ' ', '0','-1','1.5','1e2','Infinity','3x']) assert.equal(x.marketQuote(listing,qty,me,{},now).ready,false,qty);
assert.equal(x.marketQuote(listing,'8',me,{},now).ready,false,'never quote server-clamped cargo');
assert.equal(x.marketQuote(listing,'2',{...me,cargoCap:3}, {},now).ready,false);
assert.equal(x.marketQuote(listing,'2',{...me,cargoCap:undefined}, {},now).ready,false);
assert.equal(x.marketQuote({...listing,sellerId:'buyer'},'1',me,{},now).ready,false);
assert.equal(x.marketQuote(listing,'1',{...me,loc:'uptown'}, {},now).ready,false);
assert.equal(x.marketQuote(listing,'1',me,{},now+60001).ready,false);
assert.equal(x.marketQuote({...listing,kind:'order',wanted:8},'1',me,{},now).net,null,'unknown fee is not zero');
assert.equal(x.marketListings([{...listing,id:'a',unitPrice:20},{...listing,id:'b',unitPrice:3}],{sort:'price'})[0].id,'b');
assert.equal(x.marketListings([listing],{direction:'sell'}).length,0);
assert.equal(x.bank(me).cleared,230);
assert.equal(x.bank({bank:20,bankInTransit:30}).cleared,null);
assert.equal(x.bank({}).pocket,null);
assert.equal(x.travel({...me,jailSeconds:10},20,'uptown').ready,false);
assert.equal(x.travel(me,20,'uptown').after,980);
assert.equal(x.travel(me,undefined,'uptown').ready,false);
assert.equal(x.travel({...me,hospSeconds:10},20,'uptown').ready,true,'actual travel only blocks jail');
assert.equal(x.defence({gun:null,vest:null,ammo:0}).length,3);
assert.equal(x.progress([{id:'commerce',name:'Trade',xp:20,nextAt:50}])[0].remaining,30);
assert.equal(x.progress([{id:'commerce',xp:20,nextAt:null}])[0].remaining,null);
assert.equal(x.progress([{id:'wetwork',xp:0,nextAt:20}])[0].tab,'pvp');
assert.equal(x.crew({members:2},4).open,2);
assert.equal(x.crew({members:2}).open,null);
assert.equal(x.access({level:2},5),'Requires level 5. You are level 2.');
assert.match(x.access({},5),/Refresh/);
assert.equal(x.activityReceipts([{actor:'a',tab:'market'},{actor:'b',tab:'market'},{actor:'a',tab:'life'}],'a','market').length,1);
console.log('decision guide: quotes, capacity, bank, travel, progress, access and privacy passed');
